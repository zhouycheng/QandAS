const assert = require('node:assert/strict')
const fs = require('node:fs')
const preferences = require('../miniprogram/repositories/preference-repository.js')
const { defaultPreset, countOptions, timeLimitSeconds, describePreset, routeForPreset } = require('../miniprogram/utils/practice-presets.js')
const { normalizePreferences } = require('../miniprogram/utils/preferences.js')
const { PracticePresetsViewModel } = require('../miniprogram/viewmodels/practice-presets-viewmodel.js')
const { BankDetailViewModel } = require('../miniprogram/viewmodels/bank-detail-viewmodel.js')
const { PracticeViewModel } = require('../miniprogram/viewmodels/practice-viewmodel.js')
const { PracticeSession } = require('../miniprogram/models/practice-session.js')
const { serializeSession, normalizeSession } = require('../miniprogram/models/practice-session-state.js')
const { preparePracticeRoute } = require('../miniprogram/repositories/practice-launch.js')
const online = require('../miniprogram/repositories/online-practice.js')
const trials = require('../miniprogram/repositories/trial-practice.js')
const auth = require('../miniprogram/repositories/auth-repository.js')
const http = require('../miniprogram/repositories/http-gateway.js')
const copy = value => value === undefined ? undefined : JSON.parse(JSON.stringify(value))
function memory() { const data = {}; return require('./helpers/encrypted-storage.js').encrypted({ full: false, get: key => copy(data[key]), set(key, value) { if (this.full) throw new Error('存储已满'); data[key] = copy(value) }, remove: key => delete data[key] }) }
async function main() {
  for (const page of ['bank-detail', 'practice-presets']) {
    const config = JSON.parse(fs.readFileSync(require.resolve('../miniprogram/page/' + page + '/index.json'), 'utf8'))
    assert.equal(config.usingComponents['bottom-sheet'], '/components/bottom-sheet/index', page + ' 使用同一个共享弹层')
  }
  const store = memory()
  assert.equal(defaultPreset(preferences.getPreferences(store)).name, '日常练习')
  for (const [total, expected] of [[8, ['ALL']], [25, [5, 10, 20, 'ALL']], [80, [10, 20, 40, 'ALL']], [165, [20, 40, 80, 'ALL']]]) assert.deepEqual(countOptions(total, 20).map(o => o.value), expected)
  assert(countOptions(1500, 20).at(-1).disabled)
  assert.equal(timeLimitSeconds({ mode: 'test', duration: '0' }), null)
  assert.equal(timeLimitSeconds({ mode: 'test', duration: '35' }), 2100)
  assert.throws(() => timeLimitSeconds({ duration: '1.5' }), /整数/)
  const editor = new PracticePresetsViewModel({ storage: store })
  editor.edit(); editor.change('name', '考前练习'); editor.change('mode', 'test'); editor.change('count', 'ALL'); editor.change('duration', 35)
  store.full = true
  assert.match(editor.save(false).data.error, /存储已满/)
  assert.equal(editor.draft.name, '考前练习')
  assert.equal(editor.load().data.presets.length, 1)
  store.full = false; editor.save(false)
  const saved = editor.load().data.presets[1]
  editor.edit(); editor.change('name', '另一个名称')
  assert.match(editor.save(false).data.error, /该配置已存在/, '不同名称的同一配置不能重复新增')
  assert.equal(editor.load().data.presets.length, 2)
  editor.edit(saved.id); editor.change('name', '我的考前练习')
  assert.equal(editor.save(false).value.id, saved.id, '重命名自己的预设正常保存')
  editor.edit(saved.id); editor.change('mode', 'practice'); editor.change('count', 20); editor.change('countInput', '20'); editor.change('duration', 0)
  assert.match(editor.save(false).data.error, /该配置已存在/, '编辑时不能改成另一已有配置')
  assert.equal(editor.load().data.presets.find(p => p.id === saved.id).mode, 'test', '冲突不覆盖原配置')
  editor.cancel()
  editor.setDefault(saved.id)
  assert.equal(defaultPreset(preferences.getPreferences(store)).id, saved.id)
  assert.match(editor.remove(saved.id).data.error, /先将其他/)
  editor.setDefault('daily'); editor.remove(saved.id)
  assert.equal(editor.load().data.presets.length, 1)
  editor.edit('daily'); editor.change('countInput', '1.5')
  assert.match(editor.save(false).data.error, /整数/)
  editor.cancel()
  const original = normalizePreferences({ autoOpenAnalysis: false, autoNextWhenCorrect: true, fontSize: 'large', practicePresets: [{ id: 'custom', name: '背题', mode: 'view', count: 'ALL', duration: 0 }], defaultPracticePresetId: 'custom' })
  preferences.savePreferences(store, original)
  const reset = preferences.resetPreferences(store)
  assert.deepEqual(reset.practicePresets, original.practicePresets)
  assert.equal(reset.defaultPracticePresetId, 'custom')
  assert.equal(reset.autoOpenAnalysis, true); assert.equal(reset.autoNextWhenCorrect, false)
  preferences.savePreferences(store, {})
  const bank = new BankDetailViewModel({ storage: store })
  bank.repository = { ...bank.repository, getSubjectSummaries: () => [], getSubjectDetail: () => null, previewRemotePracticeScope: async () => ({ availableCount: 8, selectedCount: 8 }) }
  bank.buildViewData = () => ({})
  bank.sheetTarget = { type: 'bank', bankId: 'bank', subjectId: 's', title: '章节', questionCount: 8 }
  let data = bank.buildConfigOpenResult().data
  assert.equal(data.sheetPresetName, '日常练习'); assert.equal(data.sheetCount, 'ALL')
  bank.setSheetCount('ALL'); assert.equal(bank.buildSheetData().sheetPresetName, '自定义')
  bank.selectSheetPreset(0); assert.equal(bank.sheet.count, 20)
  bank.closeConfig(); assert.equal(defaultPreset(preferences.getPreferences(store)).count, 20)
  bank.mockSelection = true; bank.sheetTarget = { type: 'bank', bankId: 'bank', title: '章节', questionCount: 8 }
  assert.equal(bank.buildConfigOpenResult().data.sheetPresets.length, 0)
  assert.equal(bank.sheet.count, 'ALL')
  assert.equal(bank.sheet.duration, 45)
  assert.equal(bank.sheet.mode, 'test'); assert.equal(bank.setSheetMode('view'), null)
  const launched = await preparePracticeRoute(store, bank.repository, { questionBankId: 'bank', selectionKind: 'NORMAL' })
  assert.equal(launched.route.mode, 'order'); assert.equal(launched.route.duration, '0'); assert.equal(launched.count, 8)
  const configStore = memory()
  const configEditor = new PracticePresetsViewModel({ storage: configStore })
  for (const feedback of ['IMMEDIATE', 'AFTER_FINISH']) for (const order of ['order', 'random']) {
    const preset = configEditor.createFromConfig('练习配置', { mode: 'practice', feedback, order, count: 20, duration: 0 }).value
    assert.equal(preset.feedback, feedback); assert.equal(preset.order, order)
    assert.match(describePreset(preset), feedback === 'IMMEDIATE' ? /即时反馈/ : /交卷后反馈/)
    assert.match(describePreset(preset), order === 'random' ? /随机/ : /顺序/)
    assert.equal(routeForPreset(preset).mode, order === 'random' ? 'practice' : 'order')
    assert.equal(routeForPreset(preset).feedback, feedback)
    configEditor.setDefault(preset.id)
    for (const selectionKind of ['NORMAL', 'WRONG', 'FAVORITE']) {
      const configured = await preparePracticeRoute(configStore, bank.repository, { questionBankId: 'bank', selectionKind })
      assert.equal(configured.route.feedback, feedback)
      assert.equal(configured.route.mode, order === 'random' ? 'practice' : 'order')
    }
  }
  assert.equal(configEditor.load().data.presets.length, 4, '反馈和顺序不同可以保存为独立预设')
  const mock = await preparePracticeRoute(configStore, bank.repository, { questionBankId: 'bank', selectionKind: 'NORMAL' }, { mode: 'test', duration: '45' })
  assert.equal(mock.route.feedback, 'AFTER_FINISH', '模拟考固定交卷后反馈')
  assert.equal(routeForPreset({ mode: 'view', feedback: 'AFTER_FINISH', order: 'random', count: 20, duration: 0 }).feedback, 'IMMEDIATE')
  configEditor.edit(); configEditor.change('name', '草稿'); configEditor.change('feedback', 'AFTER_FINISH'); configEditor.change('order', 'random'); configEditor.change('countInput', '21')
  configStore.full = true
  assert.match(configEditor.save(false).data.error, /存储/)
  assert.equal(configEditor.draft.feedback, 'AFTER_FINISH'); assert.equal(configEditor.draft.order, 'random')
  configStore.full = false
  const configBank = new BankDetailViewModel({ storage: configStore, repository: bank.repository })
  configBank.buildViewData = () => ({})
  configBank.sheetTarget = { type: 'bank', bankId: 'bank', subjectId: 's', title: '章节', questionCount: 8 }
  configBank.buildConfigOpenResult()
  assert.equal(configBank.setSheetFeedback('IMMEDIATE').data.sheetPresetName, '自定义')
  assert.equal(configBank.setSheetOrder('order').data.sheetOrder, 'order')
  assert.equal(configBank.setSheetFeedback('invalid'), null); assert.equal(configBank.sheet.feedback, 'IMMEDIATE')
  assert.equal(configBank.setSheetOrder('invalid'), null); assert.equal(configBank.sheet.order, 'order')
  configBank.setSheetCount('ALL'); configBank.setSheetFeedback('AFTER_FINISH'); configBank.setSheetOrder('random')
  configBank.saveSheetPreset()
  assert.match(configBank.sheet.presetName, /交卷后反馈·随机/)
  assert.equal(defaultPreset(preferences.getPreferences(configStore)).count, 20, '临时配置不修改默认预设')
  configBank.setSheetMode('test')
  assert.equal(configBank.setSheetFeedback('IMMEDIATE'), null); assert.equal(configBank.setSheetOrder('order'), null)
  const redo = new PracticeViewModel({ storage: store }); redo.routeOptions = { bankId: 'bank' }
  const redoUrl = new URL('https://qanda.invalid' + redo.createRedoWrongCommand(Array.from({ length: 30 }, (_, i) => 'q' + i)).command.url)
  assert.deepEqual(redoUrl.searchParams.get('ids').split(','), Array.from({ length: 30 }, (_, i) => 'q' + i), '重练错题保留结果页列出的全部题目')
  assert.equal(redoUrl.searchParams.get('count'), '20', '默认预设仍用于生成练习设置，但不截断已明确选择的题目')
  preferences.savePreferences(store, { practicePresets: [{ id: 'all', name: '全部', mode: 'practice', count: 'ALL', duration: 0 }] })
  await assert.rejects(preparePracticeRoute(store, { previewRemotePracticeScope: async () => ({ availableCount: 1500, selectedCount: 1000 }) }, { questionBankId: 'bank' }), /缩小范围/)
  preferences.savePreferences(store, { autoOpenAnalysis: false, autoNextWhenCorrect: true })
  let id = 0
  http.request = async (method, path, body) => {
    if (path === '/question-banks/bank') return { ok: true, data: { id: 'bank', name: '题库', contentVersion: 1, questionCount: 2 } }
    assert(['/practice/sessions', '/practice/trial-snapshots'].includes(path), path)
    assert.equal(body.timeLimitSeconds, null, '模拟考不限时不能回落为十分钟')
    return { ok: true, data: { id: 's' + ++id, questionBankId: 'bank', version: 1, status: 'IN_PROGRESS', feedback: body.feedback, configuration: { mode: body.mode, timeLimitSeconds: body.timeLimitSeconds }, writer: { deviceId: body.deviceId, writerToken: 'test' }, currentIndex: 0, durationSeconds: 0,
      items: [0, 1].map(i => ({ itemId: 'i' + i, question: { id: 'q' + i, revisionId: 'r' + i, type: 'SINGLE_CHOICE', stem: '题干', options: [{ key: 'A', content: '甲' }], assetIds: [] } })), offlineGrading: [0, 1].map(i => ({ itemId: 'i' + i, correctAnswer: ['A'], explanation: '解析' })) } }
  }
  auth.saveAuth(store, { userId: 'student', provider: 'email', token: 'example' })
  const runtime = online.enable(store)
  const first = await runtime.prepare({ bankId: 'bank', mode: 'test', duration: '0' })
  const vm = new PracticeViewModel({ storage: store })
  await vm.loadOnline({ sessionId: first.id }); assert.equal(vm.session.state.isTimed, false)
  preferences.savePreferences(store, { autoOpenAnalysis: true, autoNextWhenCorrect: false })
  vm.resumeStudy(); assert.equal(vm.session.preferences.autoOpenAnalysis, false)
  const legacy = copy(first); legacy.id = 'legacy'; delete legacy.route.autoOpenAnalysis; delete legacy.route.autoNextWhenCorrect
  runtime.put(legacy.id, legacy)
  assert.equal((await runtime.prepare({ sessionId: legacy.id })).route.autoOpenAnalysis, true)
  preferences.savePreferences(store, { autoOpenAnalysis: false })
  assert.equal((await runtime.prepare({ sessionId: legacy.id })).route.autoOpenAnalysis, true)
  const state = normalizeSession(serializeSession(vm.session.getPersistedState()))
  assert.equal(state.config.autoOpenAnalysis, false)
  const model = new PracticeSession({ quiz: runtime.quiz(first), config: state.config, preferences: preferences.getPreferences(store) })
  assert.equal(model.preferences.autoOpenAnalysis, false)
  for (const feedback of ['IMMEDIATE', 'AFTER_FINISH']) {
    preferences.savePreferences(store, { autoOpenAnalysis: false, fontSize: 'normal' })
    const snapshot = await runtime.prepare({ bankId: 'bank', mode: 'order', feedback, duration: '0' })
    assert.equal(snapshot.feedback, feedback, '正式练习请求携带本次反馈方式')
    const active = new PracticeViewModel({ storage: store })
    await active.loadOnline({ sessionId: snapshot.id })
    active.session.selectOption(0)
    assert.equal(active.session.getViewData().shouldRevealAnswer, feedback === 'IMMEDIATE')
    preferences.savePreferences(store, { autoOpenAnalysis: true, fontSize: 'xxlarge' })
    active.resumeStudy()
    assert.equal(active.session.preferences.autoOpenAnalysis, false, '自动解析选项随练习固定')
    assert.equal(active.session.preferences.fontSize, 'xxlarge', '返回练习立即应用新字号')
    const resume = new PracticeViewModel({ storage: store })
    await resume.loadOnline({ sessionId: snapshot.id })
    assert.equal(resume.session.state.feedback, feedback)
    assert.equal(resume.session.preferences.autoOpenAnalysis, false)

    const trialStore = memory()
    preferences.savePreferences(trialStore, { autoOpenAnalysis: false })
    const guestSnapshot = await trials.prepare(trialStore, { bankId: 'bank', mode: 'order', feedback, duration: '0' })
    assert.equal(guestSnapshot.feedback, feedback, '游客试答请求携带本次反馈方式')
    preferences.savePreferences(trialStore, { autoOpenAnalysis: true })
    const guestResume = new PracticeViewModel({ storage: trialStore })
    await guestResume.load({ sessionId: guestSnapshot.id })
    assert.equal(guestResume.session.state.feedback, feedback)
    assert.equal(guestResume.session.preferences.autoOpenAnalysis, false)
    guestResume.session.selectOption(0)
    assert.equal(guestResume.session.getViewData().shouldRevealAnswer, feedback === 'IMMEDIATE')
  }
  runtime.queue.stop()
  const guest = memory()
  const trial = await trials.prepare(guest, { bankId: 'bank', mode: 'test', duration: '0' })
  preferences.savePreferences(guest, { autoOpenAnalysis: false })
  const trialVm = new PracticeViewModel({ storage: guest })
  await trialVm.load({ sessionId: trial.id })
  assert.equal(trialVm.session.state.isTimed, false)
  assert.equal(trialVm.session.preferences.autoOpenAnalysis, true)
  assert.equal(trials.remaining(guest), 1)
  const markup = fs.readFileSync(require.resolve('../miniprogram/components/bank-list-item/index.wxml'), 'utf8')
  assert(markup.includes('catchtap="handleConfigureTap"'))
  assert(markup.includes('aria-label="配置本次答题"'))
  assert(!describePreset(defaultPreset(preferences.getPreferences(store))).includes('undefined'))
  console.log('预设反馈与顺序、默认与临时配置隔离、正式与游客续答、会话选项固定及字号刷新通过')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
