const assert = require('node:assert/strict')
const fs = require('node:fs')
const { MyViewModel } = require('../miniprogram/viewmodels/my-viewmodel.js')
const auth = require('../miniprogram/repositories/auth-repository.js')
const { normalizePreferences } = require('../miniprogram/utils/preferences.js')
const values = {}
const storage = { get: key => values[key], set: (key, value) => { values[key] = value }, remove: key => delete values[key] }
const vm = new MyViewModel({ storage })
let data = vm.load().data
assert.equal(data.auth.displayName, '点击登录')
assert.equal(vm.tapRow('account').command.url, '/page/login/index')
assert.equal(vm.tapRow('profile').command.url, '/page/login/index')
assert.equal(vm.tapRow('account-deletion').command.url, '/page/login/index')
assert.deepEqual(data.learnRows.map(row => row.key), ['practice', 'layout', 'feedback', 'countdown', 'about'])
assert.equal(vm.tapRow('content-confirm'), null, '普通我的页不提供管理员确认入口')
auth.saveAuth(storage, { provider: 'email', userId: 'user', token: 'token', nickname: '同学', email: 'learner@example.test' })
data = vm.load().data
assert.equal(data.auth.displayName, '同学')
assert.equal(data.auth.subText, '邮箱登录')
assert.equal(data.auth.emailMasked, 'l***@example.test')
assert.equal(vm.tapRow('profile').command.url, '/page/account/index')
for (const [key, route] of Object.entries({ account: 'account', practice: 'settings', layout: 'practice-layout', countdown: 'exam-countdown', 'account-deletion': 'account-deletion', about: 'about' })) assert.equal(vm.tapRow(key).command.url, '/page/' + route + '/index')
storage.set('qandaPreferences', normalizePreferences({ autoShowExplanation: false }))
assert.equal(vm.load().data.learnRows[0].value, '仅看对错')
assert(vm.openSheet('agreement').data.sheetBody.length > 20)
assert(vm.openSheet('privacy').data.sheetBody.includes('内容安全'))
assert(!Object.hasOwn(vm.projectRemote(), 'sheet'), '刷新保留已打开协议')
assert.equal(vm.closeSheet().data.sheet, '')
assert.equal(vm.tapRow('unknown'), null)
assert.equal(vm.logout().data.auth.loggedIn, false)
assert(values.qandaPreferences)
const account = fs.readFileSync(require.resolve('../miniprogram/page/account/index.wxml'), 'utf8')
const myPage = fs.readFileSync(require.resolve('../miniprogram/page/my/index.wxml'), 'utf8')
assert.match(myPage, /class="profile"\s+bindtap="handleProfileTap"/)
assert(!myPage.includes('profile-entry'))
assert.match(myPage, /wx:if="\{\{auth.loggedIn\}\}" class="row" bindtap="confirmLogout"/)
assert.match(account, /bindtap="handleAccountDeletion"/)
assert(account.includes('open-type="chooseAvatar"'))
assert(!account.includes('currentGrade'))
console.log('我的入口、绑定资料、偏好、协议、退出保留设置通过')
