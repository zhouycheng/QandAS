const fs = require('node:fs')
const path = require('node:path')
const tokens = require('../miniprogram/utils/design-tokens.js')

function generateTheme(selector = '.portal-theme') {
  const variables = Object.entries(tokens.colors).map(([key, value]) => `  --${key}: ${value};`)
  for (const [group, values, unit] of [
    ['font', tokens.fontSizes, 'px'], ['leading', tokens.lineHeights, 'px'],
    ['space', tokens.spacing, 'rpx'], ['radius', tokens.radii, 'rpx']
  ]) for (const [key, value] of Object.entries(values)) variables.push(`  --${group}-${key}: ${value}${unit};`)
  for (const [key, value] of Object.entries(tokens.readingSizes)) variables.push(`  --reading-${key}: ${value}px;`)
  variables.push(`  --font-family: ${tokens.fontFamily};`)
  return '/* Generated by scripts/generate-design-tokens.cjs. */\n' + selector + ' {\n' + variables.join('\n') + '\n}\n'
}
function generate() {
  fs.writeFileSync(path.join(__dirname, '../miniprogram/styles/theme.wxss'), generateTheme())
  fs.writeFileSync(path.join(__dirname, '../miniprogram/styles/page-theme.wxss'), generateTheme('page'))
}
if (require.main === module) generate()
module.exports = { generateTheme, generate }
